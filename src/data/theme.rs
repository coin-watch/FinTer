fn parse_hsl(hsl_str: &str) -> Hsla {
    let hsl_str = hsl_str.trim();
    let inner = hsl_str
        .strip_prefix("hsl(")
        .and_then(|s| s.strip_suffix(")"))
        .unwrap_or(hsl_str);
    let parts: Vec<&str> = inner.split(',').map(|s| s.trim()).collect();
    if parts.len() != 3 {
        return Hsla::white();
    }
    let h = parts[0].parse::<f32>().unwrap_or(0.0) / 360.0;
    let s = parts[1].trim_end_matches('%').parse::<f32>().unwrap_or(0.0) / 100.0;
    let l = parts[2]
        .trim_end_matches('%')
        .parse::<f32>()
        .unwrap_or(100.0)
        / 100.0;
    Hsla { h, s, l, a: 1.0 }
}

