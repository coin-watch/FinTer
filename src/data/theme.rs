/// Apply a theme to the GPUI context
pub fn apply_theme(theme_name: &str, dark_mode: bool, cx: &mut gpui::App) {
    let theme = get_theme(theme_name);
    let config = if dark_mode {
        theme.to_dark_config()
    } else {
        theme.to_light_config()
    };

    gpui_component::theme::Theme::global_mut(cx).apply_config(&config);
}
